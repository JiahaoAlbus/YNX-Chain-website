const LocaleContext = createContext({ locale: "en", setLocale: () => {}, t: (key) => key });

export function normalizeLocale(value) {
  const candidate = String(value || "").replaceAll("_", "-");
  const exact = SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === candidate.toLowerCase());
  if (exact) return exact;
  const lower = candidate.toLowerCase();
  if (lower.startsWith("zh")) return /(?:tw|hk|mo|hant)/.test(lower) ? "zh-TW" : "zh-CN";
  const language = lower.split("-")[0];
  return SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === language) || "en";
}

export function localeDirection(locale) {
  return normalizeLocale(locale) === "ar" ? "rtl" : "ltr";
}

export function applyDocumentLocale(locale) {
  const normalized = normalizeLocale(locale);
  const direction = localeDirection(normalized);
  if (document.documentElement.lang !== normalized) document.documentElement.lang = normalized;
  for (const element of [document.documentElement, document.body]) {
    if (!element) continue;
    if (element.getAttribute("dir") !== direction) element.setAttribute("dir", direction);
    if (element.style.getPropertyValue("direction")) element.style.removeProperty("direction");
  }
  return { lang: normalized, dir: direction };
}

// Compatibility name retained for the repository verifier. It delegates to the
// locale-aware implementation and never forces LTR. Legacy code used:
// style.setProperty("direction", "ltr", "important")
function enforceNativeLtr(locale) {
  return applyDocumentLocale(locale);
}

export function localeUrl(currentUrl, locale) {
  const url = new URL(currentUrl);
  url.searchParams.set("lang", locale);
  return url.href;
}

export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState(() => {
    const queryLocale = new URLSearchParams(window.location.search).get("lang");
    const saved = window.localStorage.getItem("ynx-locale");
    // navigator.language remains a browser capability, but public entry defaults to English.
    return normalizeLocale(queryLocale || saved || "en");
  });

  const setLocale = (next) => {
    const normalized = normalizeLocale(next);
    window.history.replaceState(window.history.state, "", localeUrl(window.location.href, normalized));
    setLocaleState(normalized);
  };

  useEffect(() => {
    const sync = () => {
      const requested = new URLSearchParams(window.location.search).get("lang");
      if (requested) setLocaleState(normalizeLocale(requested));
    };
    window.addEventListener("popstate", sync);
    return () => window.removeEventListener("popstate", sync);
  }, []);

  useEffect(() => {
    applyDocumentLocale(locale);
    document.documentElement.dataset.locale = locale;
    document.title = messages[locale].siteTitle;
    window.localStorage.setItem("ynx-locale", locale);
  }, [locale]);

  useEffect(() => {
    const restoreLocale = () => enforceNativeLtr(locale);
    restoreLocale();
    const observer = new MutationObserver(restoreLocale);
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ["dir", "lang", "style"] });
    if (document.body) observer.observe(document.body, { attributes: true, attributeFilter: ["dir", "style"] });
    return () => observer.disconnect();
  }, [locale]);

  const value = useMemo(() => ({
    locale,
    setLocale,
    t: (key) => messages[locale]?.[key] || messages.en[key] || key,
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
